def align_x(r, align):
    return r[0] if align == 'left' else (r[2] if align == 'right' else (r[0] + r[2]) / 2)


def backdrop(d):
    W, H, HH = L['width'], L['height'], L['headerHeight']
    S = L['styles']
    d.rectangle([0, 0, p(W), p(H)], fill=GROUND)
    d.rectangle([0, 0, p(W), p(HH)], fill=HEADER)
    d.rectangle([0, p(HH - 2), p(W), p(HH)], fill=HEADER_RULE)

    for x, y in L['screws']:
        disc(d, x, y, 3.2, fill=SCREW, outline=(0, 0, 0), width=0.6)
        stroke(d, [(x - 2.2, y - 2.2), (x + 2.2, y + 2.2)], (34, 34, 34), 0.8)

    wm = L['wordmark']
    cy = HH / 2 + 1
    second = wm[0] + text_width('FILTER', S['wordmark']) + L['wordmarkGap']
    for ink, units in ((INK, None), (HEADER, 0.32)):
        lettering(d, 'FILTER', S['wordmark'], ink, wm[0], cy, stroke_units=units)
        lettering(d, 'DRUM', S['wordmark'], ink, second, cy, stroke_units=units)
    dv = L['headerDivider']
    d.rectangle([p(dv), p(16), p(dv + 1), p(40)], fill=DIVIDER)

    for sec in L['sections']:
        r = sec['rect']
        round_rect(d, [r[0] + 0.5, r[1] + 0.5, r[2] - 0.5, r[3] - 0.5], L['sectionRadius'], fill=SECTION,
                   outline=SECTION_EDGE, width=1.2)
        if sec['badge']:
            bx, by = sec['badgeCentre']
            disc(d, bx, by, L['badgeRadius'], outline=SECTION_EDGE, width=1.3)
            lettering(d, sec['badge'], S['badge'], INK, bx, by, 'centre')
        b = sec['titleBox']
        round_rect(d, b, 2, fill=SECTION, outline=SECTION_EDGE, width=1.2)
        c = (b[1] + b[3]) / 2
        lettering(d, sec['title'], S['title'], INK, b[0] + 8, c)
        if sec['subtitle']:
            lettering(d, sec['subtitle'], S['subtitle'], INK_SOFT, sec['subtitleLeft'], c)

    for bl in L['blocks']:
        r = bl['rect']
        round_rect(d, [r[0] + 0.5, r[1] + 0.5, r[2] - 0.5, r[3] - 0.5], 2, outline=BLOCK_EDGE, width=1)
        left = r[0] + L['blockCaptionInset']
        w = text_width(bl['caption'], S['block'])
        gap = L['blockCaptionGap']
        d.rectangle([p(left - gap), p(r[1] - 2), p(left + w + gap), p(r[1] + 2)], fill=SECTION)
        lettering(d, bl['caption'], S['block'], INK, left, r[1])

    for x, y, left in L['chevrons']:
        k = -1 if left else 1
        stroke(d, [(x - 5 * k, y - 10), (x + 4 * k, y), (x - 5 * k, y + 10)], SECTION_EDGE, 2.2)

    for r in L['rules']:
        d.rectangle([p(r[0]), p(r[1]), p(r[2]) - 1, p(r[3]) - 1], fill=RULE)

    bz = L['screenBezel']
    for s in L['screens']:
        r = s['rect']
        round_rect(d, [r[0] - bz + 0.5, r[1] - bz + 0.5, r[2] + bz - 0.5, r[3] + bz - 0.5], 4, fill=BEZEL,
                   outline=BEZEL_EDGE, width=1)

    for c in L['captions']:
        r, st = c['rect'], c['style']
        cy = (r[1] + r[3]) / 2
        x = align_x(r, c['align'])
        if st == 'block':
            lettering(d, c['text'], S['block'], INK, x, cy, c['align'])
        elif st == 'field':
            lettering(d, c['text'], S['label'], INK, x, cy, c['align'])
        else:
            lettering(d, c['text'], S['note'], INK_SOFT, x, cy, c['align'])


# ---------------------------------------------------------------------------
# The wear - PanelWear.h's marks, composited with their alphas
# ---------------------------------------------------------------------------
def colour(name):
    return tuple(L['wear']['colours'][name])


def layer(img):
    """A clear layer the size of the panel, and something to draw on it."""
    o = Image.new('RGBA', img.size, (0, 0, 0, 0))
    return o, ImageDraw.Draw(o)


def radial(img, cx, cy, radius, rgb, stops):
    """A radial gradient over a disc: `stops` are (fraction of radius,
    alpha), piecewise linear, as CGradient draws them."""
    R = p(radius)
    size = int(math.ceil(R)) * 2 + 2
    mask = Image.new('L', (size, size), 0)
    md = ImageDraw.Draw(mask)
    c = size / 2
    steps = max(8, min(96, int(R / 2)))
    for i in range(steps, -1, -1):          # outside in: each ring overwrites the last
        t = i / steps
        a = stops[-1][1]
        for (t0, a0), (t1, a1) in zip(stops, stops[1:]):
            if t0 <= t <= t1:
                a = a0 + (a1 - a0) * ((t - t0) / (t1 - t0) if t1 > t0 else 0)
                break
        rr = R * t
        md.ellipse([c - rr, c - rr, c + rr, c + rr], fill=int(round(a)))
    patch = Image.new('RGBA', (size, size), rgb + (0,))
    patch.putalpha(mask)
    x, y = int(round(p(cx) - c)), int(round(p(cy) - c))
    # clip the patch to the panel before compositing
    sx, sy = max(0, -x), max(0, -y)
    ex, ey = min(size, img.width - x), min(size, img.height - y)
    if ex > sx and ey > sy:
        img.alpha_composite(patch.crop((sx, sy, ex, ey)), (x + sx, y + sy))


def soft_disc(img, cx, cy, radius, rgb, alpha):
    radial(img, cx, cy, radius, rgb, [(0, alpha), (0.5, alpha * 0.55), (1, 0)])


def wear_line(d, line, rgb):
    """Half strength in the first and last thirds, as wearLine() draws it."""
    pts = [(line['pts'][i], line['pts'][i + 1]) for i in range(0, len(line['pts']), 2)]
    n = len(pts)
    if n < 2:
        return
    a, b = max(1, n // 3), max(max(1, n // 3) + 1, n - n // 3)
    half = line['a'] // 2
    stroke(d, pts[0:a + 1], rgb + (half,), line['w'])
    stroke(d, pts[a:min(b + 1, n)], rgb + (line['a'],), line['w'])
    if b < n - 1:
        stroke(d, pts[b:n], rgb + (half,), line['w'])


def panel_wear(img):
    W = L['wear']
    dust = colour('dust')
    for x, y, r, a in W['haze']:
        soft_disc(img, x, y, r, dust, a)
    for r, fx, fy, a in W['drifts']:
        o, od = layer(img)
        if fx:
            n = r[2] - r[0]
            for i in range(int(p(n))):
                t = i / p(n)
                x = p(r[0]) + i if fx < 0 else p(r[2]) - 1 - i
                od.line([(x, p(r[1])), (x, p(r[3]) - 1)], fill=dust + (int(round(a * (1 - t))),))
        else:
            n = r[3] - r[1]
            for i in range(int(p(n))):
                t = i / p(n)
                y = p(r[1]) + i if fy < 0 else p(r[3]) - 1 - i
                od.line([(p(r[0]), y), (p(r[2]) - 1, y)], fill=dust + (int(round(a * (1 - t))),))
        img.alpha_composite(o)
    for cx, cy, inner, peak, outer, a in W['rings']:
        radial(img, cx, cy, outer, dust, [(0, 0), (inner / outer, 0), (peak / outer, a), (1, 0)])
    o, od = layer(img)
    for line in W['scratches']:
        wear_line(od, line, colour('scratch'))
    img.alpha_composite(o)
    o, od = layer(img)
    for x, y, r, a in W['specks']:
        disc(od, x, y, r, fill=colour('speck') + (a,))
    for line in W['fibres']:
        wear_line(od, line, colour('speck'))
    img.alpha_composite(o)


def glass_wear(img, index):
    G = L['wear']['glass'][index]
    o, od = layer(img)
    for ridges in G['prints']:
        for ridge in ridges:
            pts = [(ridge['pts'][i], ridge['pts'][i + 1]) for i in range(0, len(ridge['pts']), 2)]
            stroke(od, pts, colour('print') + (ridge['a'],), ridge['w'])
    img.alpha_composite(o)
    o, od = layer(img)
    for x, y, r, a in G['dust']:
        disc(od, x, y, r, fill=colour('glassDust') + (a,))
    for line in G['fibres']:
        wear_line(od, line, colour('glassDust'))
    img.alpha_composite(o)


def knob_wear(img, kw, cx, cy, body, a):
    """Relative to the pointer at `a` (VSTGUI degrees), as Knob::draw does."""
    cap_r = body * 0.78
    if kw['knurl']:
        o, od = layer(img)
        rr = (cap_r + body) / 2
        w = body - cap_r
        od.ellipse([p(cx - rr - w / 2), p(cy - rr - w / 2), p(cx + rr + w / 2), p(cy + rr + w / 2)],
                   outline=colour('knurlDust') + (kw['knurl'],), width=max(1, round(p(w))))
        img.alpha_composite(o)
    if kw['sheen']:
        soft_disc(img, cx - cap_r * 0.25, cy - cap_r * 0.3, cap_r * 0.55, colour('sheen'), kw['sheen'])
    o, od = layer(img)
    for radius, start, span, width, alpha in kw['scuffs']:
        rr = cap_r * radius
        st = a + start
        od.arc([p(cx - rr), p(cy - rr), p(cx + rr), p(cy + rr)], st, st + span,
               fill=colour('scuff') + (alpha,), width=max(1, round(p(width))))
    for radius, ang, r, alpha in kw['grit']:
        x, y = vstgui_angle(cx, cy, body * radius, a + ang)
        disc(od, x, y, r, fill=colour('knurlDust') + (alpha,))
    img.alpha_composite(o)


def cap(d, cx, cy, radius):
    """A black cap lit from the top left: concentric discs, the light
    drifting towards the highlight as they shrink."""
    steps = 24
    for i in range(steps):
        t = i / (steps - 1)
        rr = radius * (1 - t * 0.85)
        ox, oy = -radius * 0.25 * t, -radius * 0.35 * t
        col = blend((5, 5, 5), (22, 22, 22), min(1, t / 0.4)) if t < 0.4 else blend((22, 22, 22), (58, 58, 58), (t - 0.4) / 0.6)
        disc(d, cx + ox, cy + oy, rr, fill=col)


def knob(img, c, index):
    d = ImageDraw.Draw(img)
    S = L['styles']
    r, dia = c['rect'], c['diameter']
    cx, cy = (r[0] + r[2]) / 2, r[1] + dia / 2
    outer = dia / 2
    body = outer - (6 if dia >= 44 else 5)
    v = max(0.0, min(1.0, c['value']))
    if c['reversed']:
        v = 1.0 - v
    a = 135 + 270 * v

    for i in range(11):
        t = 135 + 27 * i
        long_ = i in (0, 5, 10)
        stroke(d, [vstgui_angle(cx, cy, body + 1.5, t), vstgui_angle(cx, cy, outer - (0 if long_ else 1.8), t)],
               TICK, 1.3 if long_ else 0.9)
    ends = c.get('ends')
    if ends or dia >= 52:
        lo_t, hi_t = ends if ends else (('-', '+') if c['bipolar'] else ('0', '10'))
        lo = from_top(cx, cy, outer + 2, -138)
        hi = from_top(cx, cy, outer + 2, 138)
        lettering(d, lo_t, S['tick'], TICK, lo[0] - 2, lo[1] + 4, 'right')
        lettering(d, hi_t, S['tick'], TICK, hi[0] + 2, hi[1] + 4)

    n_teeth = 36 if dia >= 64 else 28
    teeth = [vstgui_angle(cx, cy, body if i % 2 == 0 else body - 1.4, 360 * i / (2 * n_teeth)) for i in range(2 * n_teeth)]
    d.polygon([pt(x, y) for x, y in teeth], fill=KNOB_BODY, outline=KNOB_RIM)
    cap(d, cx, cy, body * 0.78)
    disc(d, cx, cy, body * 0.78, outline=(0, 0, 0), width=0.8)
    knob_wear(img, L['wear']['controls'][index], cx, cy, body, a)
    d = ImageDraw.Draw(img)
    stroke(d, [vstgui_angle(cx, cy, body * 0.15, a), vstgui_angle(cx, cy, body - 0.5, a)], INK,
           2.4 if dia >= 60 else (2.2 if dia >= 44 else 1.8))

    top = r[1] + dia + L['knobGap']
    lettering(d, c['text'], S['value'], INK, cx, top + L['knobValueH'] / 2, 'centre')
    lettering(d, c['label'], S['label'], INK, cx, top + L['knobValueH'] + L['knobLabelH'] / 2, 'centre')


def selector(img, c, index):
    d = ImageDraw.Draw(img)
    S = L['styles']
    g = c['selector']
    cx, cy, rad = g['cx'], g['cy'], g['radius']
    names = c['names']
    cur = int(round(c['value'] * (len(names) - 1)))
    for i, name in enumerate(names):
        t = g['angles'][i]
        on = i == cur
        stroke(d, [from_top(cx, cy, rad + 2.5, t), from_top(cx, cy, rad + 8, t)], RED if on else TICK, 2 if on else 1.6)
        b = g['labelBoxes'][i]
        lettering(d, name, S['label'], INK if on else INK_DIM, b[0], (b[1] + b[3]) / 2)

    a = g['angles'][cur]
    disc(d, cx, cy, rad * 0.8, fill=(11, 11, 11), outline=(68, 68, 68), width=0.8)
    o, od = layer(img)
    for radius, ang, r, alpha in L['wear']['controls'][index]['grit']:
        x, y = from_top(cx, cy, rad * 0.8 * radius, a + ang)
        disc(od, x, y, r, fill=colour('knurlDust') + (alpha,))
    img.alpha_composite(o)
    d = ImageDraw.Draw(img)
    tip = from_top(cx, cy, rad + 3, a)
    left = from_top(cx, cy, 8, a - 90)
    right = from_top(cx, cy, 8, a + 90)
    tail = from_top(cx, cy, rad, a + 180)
    beak = [tip, right] + quad(right, tail, left)
    d.polygon([pt(x, y) for x, y in beak], fill=(26, 26, 26))
    stroke(d, beak + [tip], (0, 0, 0), 0.8)
    stroke(d, [from_top(cx, cy, 2, a), tip], INK, 1.8)
    lettering(d, c['label'], S['label'], INK, cx, g['nameY'], 'centre')


def key(d, r, radius):
    """A black push-button: shadow, a face lit from above, a rim."""
    round_rect(d, r, radius + 0.5, fill=BEZEL)
    face = [r[0] + 1.5, r[1] + 1, r[2] - 1.5, r[3] - 2.5]
    steps = 12
    for i in range(steps):
        t0 = i / steps
        y0 = face[1] + (face[3] - face[1]) * t0
        y1 = face[1] + (face[3] - face[1]) * (i + 1) / steps
        col = blend((44, 44, 44), (18, 18, 18), t0)
        d.rectangle([p(face[0] + 0.6), p(y0), p(face[2] - 0.6), p(y1)], fill=col)
    round_rect(d, face, radius, outline=KEY_EDGE, width=0.7)


def lamp_at(d, x, y, level, bezel=5.5, lamp=4.0):
    disc(d, x, y, bezel, fill=(0, 0, 0), outline=SECTION_EDGE, width=1)
    if level > 0:
        disc(d, x, y, lamp, fill=blend(LAMP_OFF, LAMP_ON, level))
    else:
        disc(d, x, y, lamp, fill=LAMP_OFF)
    disc(d, x - 1.2, y - 1.2, 1.3, fill=blend(LAMP_OFF, (255, 255, 255), 0.25))


def step(img, c):
    d = ImageDraw.Draw(img)
    S = L['styles']
    G = L['step']
    r = c['rect']
    on = c['value'] >= 0.5
    cx = (r[0] + r[2]) / 2
    ly = r[1] + G['led']
    k = [r[0], r[1] + G['keyTop'], r[2], r[1] + G['keyBottom']]
    w = k[2] - k[0]
    lens = [k[0] + w * 0.2, k[1] + 6, k[2] - w * 0.2, k[1] + 11]
    ny = r[1] + G['number']
    num = str(c['number'])
    if c['disabled']:
        x = k[0] + 0.5
        while x < k[2]:
            stroke(d, [(x, k[1] + 0.5), (min(x + 3, k[2] - 0.5), k[1] + 0.5)], (106, 104, 98), 1.1)
            stroke(d, [(x, k[3] - 0.5), (min(x + 3, k[2] - 0.5), k[3] - 0.5)], (106, 104, 98), 1.1)
            x += 6
        y = k[1] + 0.5
        while y < k[3]:
            stroke(d, [(k[0] + 0.5, y), (k[0] + 0.5, min(y + 3, k[3] - 0.5))], (106, 104, 98), 1.1)
            stroke(d, [(k[2] - 0.5, y), (k[2] - 0.5, min(y + 3, k[3] - 0.5))], (106, 104, 98), 1.1)
            y += 6
        if on:
            round_rect(d, lens, 1.5, outline=RED, width=1)
        stroke(d, [(cx - 3, ly), (cx + 3, ly)], INK_FAINT, 1.2)
        lettering(d, num, S['step'], INK_FAINT, cx, ny, 'centre')
        return
    disc(d, cx, ly, 2.8, fill=(0, 0, 0), outline=(58, 58, 58), width=0.8)
    disc(d, cx, ly, 2.0, fill=(34, 32, 28))
    key(d, k, 3)
    if on:
        o, od = layer(img)
        round_rect(od, [lens[0] - 3, lens[1] - 3, lens[2] + 3, lens[3] + 3], 3, fill=(255, 59, 47, 80))
        img.alpha_composite(o)
        d = ImageDraw.Draw(img)
        round_rect(d, lens, 1.5, fill=LAMP_ON)
        round_rect(d, [lens[0] + 1, lens[1] + 0.8, lens[2] - 1, lens[1] + 2], 1, fill=blend(LAMP_ON, (255, 255, 255), 0.35))
    else:
        round_rect(d, lens, 1.5, fill=LENS_OFF, outline=(0, 0, 0), width=0.5)
    lettering(d, num, S['step'], INK if on else INK_DIM, cx, ny, 'centre')


