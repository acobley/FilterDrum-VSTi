#!/usr/bin/env python3
"""Draw the plug-in's panel into docs/panel.png.

WHY IT DOES NOT PARSE THE SOURCE. This script asks the plug-in:
tools/dump-layout.cpp is compiled against source/FilterDrumLayout.h,
FilterDrumReadouts.cpp and FilterDrumDsp.cpp and prints every position,
every piece of text and all four screens' curves as JSON - from the SAME
code the editor runs. This script only draws. A layout change that breaks
the tool fails to compile rather than drawing last week's panel.

What it cannot show is VSTGUI's own rendering: this is a reconstruction
from the same numbers in the panel's palette (FilterDrumPanelViews.h),
not a screenshot. It exists so that a control in the wrong place HERE is
a control in the wrong place in the plug-in - the only way to judge a
layout without a host.

THE BLACK PANEL, "MIRROR COLUMNS" (branch PolivoksUI, Oct 2026), from
Designs/FilterDrum-Polivoks-3-MirrorColumns.png - R2Synth 1.1's look, and
this script is R2Synth's tools/render-panel.py taught FilterDrum's parts:
white printing on black, knurled knobs, the chicken-head selector, black
step keys, small colour OLED screens, and every letter in the 70s sci-fi
lettering - stroked from the glyphs dump-layout prints, parsed by
SciFiLettering.h, so this script keeps no copy of the face.

THE WEAR ("Studio Worn"): dust, hairlines, scuffed knob tops, dust and
fingerprints on the glass - every mark generated by source/PanelWear.h and
printed by dump-layout under "wear", so this script draws the same marks
the plug-in does and keeps no seed of its own.

    python3 tools/render-panel.py [out.png] [sampleRate]

Needs a C++ compiler, Pillow, and the VST3 SDK for one header-only file:
external/vst3sdk (the in-tree clone), or VST3_SDK_ROOT in the environment.
"""

import json
import os
import shutil
import subprocess
import sys
import tempfile

import math

from PIL import Image, ImageDraw

RATE = sys.argv[2] if len(sys.argv) > 2 else None
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))
SCALE = 2          # the PNG is drawn at 2x so the text is legible
SS = 4             # ...from a 4x drawing, for smooth curves


# ---------------------------------------------------------------------------
# Ask the plug-in
# ---------------------------------------------------------------------------
def dump_layout():
    sdk = os.environ.get('VST3_SDK_ROOT') or os.path.join(ROOT, 'external', 'vst3sdk')
    if not os.path.exists(os.path.join(sdk, 'pluginterfaces', 'vst', 'vsttypes.h')):
        raise SystemExit('render-panel.py: no VST3 SDK at %s - run ./setup-xcode.sh once, '
                         'or set VST3_SDK_ROOT' % sdk)
    cxx = shutil.which('c++') or shutil.which('g++') or shutil.which('clang++')
    if not cxx:
        raise SystemExit('render-panel.py: no C++ compiler. Refusing to draw the panel '
                         'from a second copy of its numbers.')
    src = os.path.join(ROOT, 'source')
    with tempfile.TemporaryDirectory() as tmp:
        exe = os.path.join(tmp, 'dump-layout')
        subprocess.run([cxx, '-std=c++17', '-O1', '-I' + sdk, '-I' + src, '-o', exe,
                        os.path.join(ROOT, 'tools', 'dump-layout.cpp'),
                        os.path.join(src, 'FilterDrumReadouts.cpp'),
                        os.path.join(src, 'FilterDrumParams.cpp'),
                        os.path.join(src, 'FilterDrumDsp.cpp'),
                        os.path.join(src, 'FilterDrumTransport.cpp')], check=True)
        out = subprocess.run([exe] + ([RATE] if RATE else []), check=True, capture_output=True, text=True).stdout
    return json.loads(out)


